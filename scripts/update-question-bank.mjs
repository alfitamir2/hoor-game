import { readFileSync, writeFileSync } from 'node:fs';

// The reviewed source stays editable; compilation rejects incomplete updates.
const source = readFileSync('content/questions-source.md', 'utf8');
const ages = ['under_8', '8_to_15', '16_plus', 'parents'];
const corrections = {
  'bank1-q015': 'بأي أداة نعرف الوقت؟',
  'bank1-q033': 'أي حيوان من الآتي يُربّى عادةً للحصول على الحليب؟',
  'bank1-q050': 'أي حيوان معروف بدخوله في سبات شتوي في بعض المناطق؟',
  'bank2-q022': 'أي كوكبين في المجموعة الشمسية ليس لهما أقمار طبيعية معروفة؟',
  'bank3-q001': 'أي سرعة تكون نفسها لدى جميع المراقبين العطاليين في النسبية الخاصة؟',
  'bank3-q008': 'في نظام معزول تمامًا، ماذا يحدث للطاقة الكلية؟',
  'bank3-q009': 'أي الموجات الكهرومغناطيسية الآتية أعلى طاقة للفوتون؟',
};
const explanations = {
  'bank3-q001': 'سرعة الضوء في الفراغ ثابتة لجميع المراقبين العطاليين. الكتلة السكونية أيضًا خاصية ثابتة للجسم، لذلك حُدّد السؤال بالسرعة.',
  'bank3-q008': 'النظام المعزول لا يتبادل الطاقة مع محيطه، فتُحفظ طاقته الكلية، مع إمكانية تحولها بين صور مختلفة.',
};
const banks = source.split(/^## البنك.*$/m).slice(1);
if (banks.length !== 4) throw new Error('Expected four age banks');
const questions = [];
for (const [bankIndex, bank] of banks.entries()) {
  const refs = new Map();
  for (const line of bank.split('\n')) {
    const match = line.match(/^\[(\d+)\]:\s*(.*)$/);
    if (match) refs.set(match[1], match[2]);
  }
  const matches = [...bank.matchAll(/^### (\d+)\.\s*([\s\S]*?)(?=^### |\Z|(?![\s\S]))/gm)];
  if (matches.length !== 100) throw new Error(`Bank ${bankIndex + 1}: expected 100 questions, got ${matches.length}`);
  for (const match of matches) {
    const n = Number(match[1]);
    const body = match[2];
    const id = `bank${bankIndex + 1}-q${String(n).padStart(3, '0')}`;
    const options = [...body.matchAll(/^- ([أبجد])\)\s*(.+)$/gm)].map(m => m[2].trim());
    const answer = body.match(/^الإجابة الصحيحة:\s*([أبجد])\)\s*(.+)$/m);
    const original = body.split(/^- أ\)/m)[0].trim();
    const q = corrections[id] || original;
    if (options.length !== 4 || new Set(options).size !== 4 || !answer || options['أبجد'.indexOf(answer[1])] !== answer[2].trim()) throw new Error(`Invalid options/answer: ${id}`);
    const refIds = [...(body.match(/^التوثيق:\s*(.*)$/m)?.[1] || '').matchAll(/\[(\d+)\]/g)].map(m => m[1]);
    if (!refIds.length || refIds.some(ref => !refs.has(ref))) throw new Error(`Missing references: ${id}`);
    const preceding = bank.slice(0, match.index);
    const headings = [...preceding.matchAll(/^## (.+)$/gm)];
    let category = headings.at(-1)?.[1] || (bankIndex === 0 ? 'معارف البراعم' : bankIndex === 1 ? 'الحساب والمنطق' : bankIndex === 2 ? 'الفيزياء' : 'التربية والحياة الأسرية');
    if (category === 'مراجع القسم') throw new Error(`Unexpected section: ${id}`);
    // Tag by content without adding harder questions to younger age groups.
    const religious = /القرآن|سورة|سور |النبي|رسول الله|الإسلام|الإيمان|الصلاة|رمضان|الوضوء|البخاري|مسلم|صحابي/.test(q);
    const math = /ناتج|العدد|نصف|ربع|جمع|طرح|يساوي|متتابعة|احتمال|معادلة|جذر|مربع العدد|محيط|مساحة|مثلث|أضلاع|منطق|كم .*\d/.test(q) || /رياضيات|الحساب/.test(category);
    questions.push({ id, age: ages[bankIndex], category, q, options, correctText: answer[2].trim(), modes: ['basic', ...(religious ? ['quran'] : []), ...(math ? ['genius'] : [])], hikmah: explanations[id] || `الإجابة الصحيحة: ${answer[2].trim()}.`, sources: refIds.map(ref => ({ ref, citation: refs.get(ref) })) });
  }
}
const normalized = q => q.normalize('NFKC').replace(/[\u064B-\u065F\u0670]/g, '').replace(/[^\p{L}\p{N}]/gu, '');
const seen = new Map();
for (const q of questions) {
  const key = `${q.age}:${normalized(q.q)}`;
  if (seen.has(key)) throw new Error(`Duplicate question: ${q.id} / ${seen.get(key)}`);
  seen.set(key, q.id);
}
writeFileSync('public/question-bank.js', `// Generated by scripts/update-question-bank.mjs; edit content/questions-source.md instead.\nwindow.HoorQuestionBank = ${JSON.stringify({ version: '2026-10-31.1', questions }, null, 2)};\n`);
console.log(`Compiled ${questions.length} questions; 100 per age group; valid options, references and unique texts per group.`);